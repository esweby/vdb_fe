begin;
create extension if not exists pgtap with schema extensions;
select plan(23);
select has_table('public', 'community_job_gate', 'community recalculation has a shared gate');
select has_function('public', 'acquire_community_job', array['boolean'], 'the server acquires the gate atomically');
select is((select schedule from cron.job where jobname = 'community-scores-fallback'), '15 3 * * *', 'a second fixed daily run is scheduled fifteen minutes later');
select matches((select command from cron.job where jobname = 'community-scores-fallback'), 'invoke_community_scores_job', 'the second run uses the fresh-nonce wrapper');
select ok(not has_function_privilege('anon', 'public.acquire_community_job(boolean)', 'EXECUTE'), 'anon cannot acquire the gate');
select ok(not has_function_privilege('authenticated', 'public.acquire_community_job(boolean)', 'EXECUTE'), 'users cannot bypass the Edge Function gate');
select ok((select relrowsecurity from pg_class where oid = 'public.community_job_gate'::regclass), 'gate state has RLS');
select is(to_regprocedure('public.replace_community_scores(jsonb,bigint)'), null, 'the old unguarded score writer is removed');
select is(to_regprocedure('public.replace_community_synergies(jsonb,jsonb,bigint)'), null, 'the old unguarded synergy writer is removed');

-- Isolate fixtures from existing local job state.
update public.community_job_gate set token = null, lease_until = null, last_started_at = null;
set local role service_role;
select is(public.acquire_community_job(false)->>'status', 'started', 'the server admits the first run');
reset role;
create temporary table first_lease as select token, last_started_at from public.community_job_gate;
set local role service_role;
select is(public.acquire_community_job(false)->>'reason', 'running', 'another user run is refused while the lease is live');
select is(public.acquire_community_job(true)->>'reason', 'running', 'the scheduled path cannot bypass a live lease');
select is((public.acquire_community_job(false)->>'retryAfter')::integer, 30, 'a running refusal returns a short delay, not the lease duration');
reset role;
select is((select last_started_at from public.community_job_gate), (select last_started_at from first_lease), 'refusals do not extend cooldown');
select lives_ok($$select public.replace_community_scores('[]', 1, (select token from first_lease))$$, 'the lease owner can publish scores');
select lives_ok($$select public.replace_community_synergies('[]', '[]', 1, (select token from first_lease))$$, 'the lease owner can publish synergies');
select public.release_community_job((select token from first_lease));
select is(public.acquire_community_job(false)->>'reason', 'cooldown', 'release does not bypass user cooldown');
select is(public.acquire_community_job(true)->>'status', 'started', 'scheduled calls bypass cooldown');
select public.release_community_job((select token from first_lease));
select ok((select token is not null from public.community_job_gate), 'an older owner cannot release the newer lease');
select throws_ok($$select public.replace_community_scores('[]', 2, (select token from first_lease))$$, '42501', null, 'an older owner cannot publish scores');
select throws_ok($$select public.replace_community_synergies('[]', '[]', 2, (select token from first_lease))$$, '42501', null, 'an older owner cannot publish synergies');
update public.community_job_gate set lease_until = clock_timestamp() - interval '1 second', last_started_at = clock_timestamp() - interval '31 seconds';
select throws_ok($$select public.replace_community_scores('[]', 3, (select token from public.community_job_gate))$$, '42501', null, 'an expired lease cannot publish even without a replacement owner');
select is(public.acquire_community_job(false)->>'status', 'started', 'an expired lease can be acquired again');
select * from finish();
rollback;
